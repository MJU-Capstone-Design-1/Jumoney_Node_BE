export const EXPECTED_KOSPI_200_LEN = 200;
const KOSPI_CODE_PATTERN = /^[A-Z0-9]{6}$/;

export function assertKospi200Codes(codes: readonly string[]): void {
  if (codes.length !== EXPECTED_KOSPI_200_LEN) {
    console.warn(
      `⚠️ KOSPI_200_CODES 길이 불일치: ${codes.length} (expected ${EXPECTED_KOSPI_200_LEN}).`,
    );
  }

  const invalidCodes = codes.filter((code) => !KOSPI_CODE_PATTERN.test(code));
  if (invalidCodes.length > 0) {
    console.warn(`⚠️ 유효하지 않은 종목코드(${invalidCodes.length}): ${invalidCodes.join(', ')}`);
  }

  const seen = new Set<string>();
  const duplicates = new Set<string>();
  for (const code of codes) {
    if (seen.has(code)) duplicates.add(code);
    seen.add(code);
  }
  if (duplicates.size > 0) {
    console.warn(`⚠️ 중복 종목코드(${duplicates.size}): ${Array.from(duplicates).join(', ')}`);
  }
}
